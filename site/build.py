def changes_page():
    def cell(s):
        return re.sub(r"`([^`]+)`", r"<code>\1</code>", esc(s))
    rows = "".join(f'<tr><td>{r["n"]}</td><td>{cell(r["who"])}<br><span class="when">{cell(r["when"])}</span></td><td>{cell(r["said"])}</td><td>{cell(r["change"])}</td><td>{cell(r["status"])}</td></tr>' for r in CHANGES["rows"])
    body = f'''<header class="mast">
  <p class="eyebrow">Change log</p>
  <h1>What changed, and who asked</h1>
  <p class="count">{len(CHANGES["rows"])} changes · feedback from {day(CHANGES["feedback_from"])} · applied {day(CHANGES["date"])}</p>
  <p class="topline">One row per piece of feedback from the meeting. “What they said” is a summary, not a quote. From here on, each case’s own history is its file history on <a href="{GH}/commits/main/use-cases">GitHub</a>.</p>
</header>
<div class="tablewrap"><table class="log"><thead><tr><th>#</th><th>Who asked</th><th>What they said</th><th>Change made</th><th>Status</th></tr></thead><tbody>{rows}</tbody></table></div>'''
    return shell("Change log · x402 Identity WG use cases", "What changed on the x402 use-case boards and who asked for it.", 1, body, "changes/")


def write(path, text):
    full = os.path.join(OUT, path)
    os.makedirs(os.path.dirname(full), exist_ok=True)
    open(full, "w", encoding="utf-8").write(text)


def main():
    diagrams = {b["id"]: {"lanes": b["lanes"], "steps": bf.checker_steps(bf.steps_for(b))} for b in BOARDS}
    verify_arrows.WHITELIST = verify_arrows.DEFAULT_WHITELIST
    buf = io.StringIO()
    with contextlib.redirect_stdout(buf):
        fails = verify_arrows.run(diagrams, False)
    print("arrows:", buf.getvalue().strip().split("\n")[-1])
    if fails:
        print(buf.getvalue())
        return 1

    shutil.rmtree(OUT, ignore_errors=True)
    tensions, err = fetch_tensions()
    if err:
        print("tensions: not loaded:", err)
    css = open(os.path.join(ROOT, "boards", "bare.css"), encoding="utf-8").read()
    write("assets/site.css", css + "\n" + open(os.path.join(ROOT, "site", "extra.css"), encoding="utf-8").read())
    shutil.copy(os.path.join(ROOT, "site", "evidence.js"), os.path.join(OUT, "assets", "evidence.js"))
    svg_css = "\n".join(l for l in css.splitlines() if l.startswith((":root", "svg ", ".lanebox", ".counter", ".life", ".a-", ".h-", ".tint", ".notebg", ".work", ".region", ".slot", ".wallet")))
    for i, b in enumerate(BOARDS):
        write(slug(b["id"]) + "/index.html", board_page(i, b, tensions, err))
        svg = bf.render_board(b["id"], b["lanes"], bf.steps_for(b))
        write(f"assets/boards/{b['id']}.svg", svg.replace(">", f' xmlns="http://www.w3.org/2000/svg"><style>{svg_css}</style>', 1))
        png = os.path.join(ROOT, "boards", "export", b["id"] + ".png")
        if os.path.exists(png):
            shutil.copy(png, os.path.join(OUT, "assets", "boards", b["id"] + ".png"))
    write("index.html", index_page(tensions, err))
    write("evidence/index.html", evidence_page())
    write("changes/index.html", changes_page())
    write(".nojekyll", "")
    print(f"wrote {len(BOARDS)} boards · {len(QUOTES)} quotes · {len(tensions)} tensions -> _site/")
    return 0


if __name__ == "__main__":
    sys.exit(main())
