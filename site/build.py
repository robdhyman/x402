MEETING = {m["n"]: m for m in EV["meetings"]}
CT = ZoneInfo("America/Chicago")


def clock(t):
    """'10:25 a.m. CT (15:25 UTC)' for an aware datetime."""
    ct = t.astimezone(CT)
    return f"{ct.hour % 12 or 12}:{ct.minute:02d} {'a.m.' if ct.hour < 12 else 'p.m.'} CT ({t:%H:%M} UTC)"


def quote_source(q):
    """Where a quote came from, in full: the call, the moment it was said, the recording, the transcript."""
    m = MEETING[q["meeting"]]
    held = datetime.date.fromisoformat(q["date"])
    rows = [("Call", f"x402 Identity Working Group meeting {m['n']} of {len(EV['meetings'])} · {held:%A}, {day(q['date'])}")]
    start = m.get("recording_start_utc")
    h, mi, se = map(int, q["time"].split(":"))
    if start and not q["chat"]:
        t0 = datetime.datetime.fromisoformat(start.replace("Z", "+00:00"))
        rows.append(("Said at", f"{clock(t0 + datetime.timedelta(hours=h, minutes=mi, seconds=se))} · {q['time']} into the recording"))
    else:
        rows.append(("Said at", f"{'chat, ' if q['chat'] else ''}{q['time']} into the recording"))
    link = CFG.get("recordings", {}).get(str(m["n"]))
    rec = f"Zoom cloud recording, started {clock(t0)}" if start else "Zoom cloud recording"
    rows.append(("Recording", f'{esc(rec)} · <a href="{esc(link)}">watch</a>' if link else f"{esc(rec)} · no public link posted"))
    rows.append(("Transcript", "Zoom transcript of the same recording; wording, speaker and time checked against it" if q["verified"] else "Zoom transcript of the same recording; not yet checked against it"))
    return '<dl class="q-src">' + "".join(f"<div><dt>{k}</dt><dd>{v if k == 'Recording' else esc(v)}</dd></div>" for k, v in rows) + "</dl>"


def quote_li(q, rel, link=True):
    where = "chat " if q["chat"] else ""
    boards = "".join(f'<a class="chip" href="{rel}{slug(b)}/index.html">{uc_tag(b)}</a>' for b in q["boards"])
    filed = " · ".join(x for x in (q["section"], q["topic"]) if x)
    anchor = f'<a class="perma" href="{rel}evidence/index.html#{q["id"]}" title="Link to this quote">#</a>' if link else ""
    return (f'<li class="q" id="{q["id"]}" data-m="{q["meeting"]}" data-s="{esc(q["speaker"].split(" (")[0])}" data-sec="{esc(q["section"] or "")}" data-b="{1 if q["boards"] else 0}">'
            f'<p class="q-meta"><span class="q-who">{esc(q["speaker"])}</span><span>{day(q["date"])}</span><span>{where}{q["time"]}</span>{boards}{anchor}</p>'
            f'<blockquote>“{esc(q["text"])}”</blockquote>'
            + (quote_source(q) if q["boards"] else "") +
            f'<p class="q-filed">{esc(filed)}</p></li>')


def tension_html(bid, ts, err):
    t = uc_tag(bid)
    new = f'{GH}/issues/new?template=tension.yml&title=%5B{t}%5D+'
    if err:
        rows = f'<p class="prose">The tension list could not be loaded at build time. <a href="{GH}/issues?q=label%3Atension">See all tensions on GitHub</a>.</p>'
    elif not ts:
        rows = '<p class="prose">None logged yet. The “Still open” row above lists what the board itself leaves undecided.</p>'
    else:
        lis = []
        for x in ts:
            state = "open" if x["open"] else "closed"
            kind = "" if x["blocking"] else '<span class="chip">non-blocking</span>'
            title = re.sub(r"^\[[^\]]+\]\s*", "", x["title"])
            lis.append(f'<li class="t {state}"><span class="t-state">{state}</span><a href="{x["url"]}">{esc(title)}</a>'
                       f'<span class="t-n">#{x["n"]} · {x["comments"]} comment{"" if x["comments"] == 1 else "s"}</span>{kind}</li>')
        rows = '<ul class="tensions">' + "".join(lis) + "</ul>"
    code, label = status(ts)
    rule = {"open": f"Not done: {label} tension{'s' if label != '1 open' else ''} must be settled first.",
            "settled": "Every logged tension is settled.",
            "none": "No tensions logged, so nothing yet says this case is done."}[code]
    return f'''<section class="uc" id="tensions" aria-labelledby="tensions-h">
<header class="uc-head"><p class="uc-no">Competing needs</p><h2 id="tensions-h">Tensions to settle</h2>
<p class="instance">A tension is a point where two needs conflict. {rule} A case is done when it has no open tension except those marked non-blocking.</p></header>
{rows}
<p class="actions"><a class="btn" href="{new}">Raise a tension</a></p>
</section>'''


def discussion_html(bid):
    num = CFG["discussions"].get(bid)
    if not (num and CFG.get("giscus_repo_id")):
        body = f'<p class="prose">Comments open here once Discussions are switched on. Until then, <a href="{GH}/issues">open an issue</a>.</p>'
    else:
        body = f'''<p class="prose">Sign in with GitHub to comment. If the box below does not load, <a href="{GH}/discussions/{num}">open this thread on GitHub</a>.</p>
<div class="giscus"></div>
<script src="https://giscus.app/client.js" data-repo="{REPO}" data-repo-id="{CFG["giscus_repo_id"]}" data-mapping="number" data-term="{num}" data-reactions-enabled="1" data-emit-metadata="0" data-input-position="top" data-theme="light" data-lang="en" data-loading="lazy" crossorigin="anonymous" async></script>'''
    return f'''<section class="uc" id="discussion" aria-labelledby="discussion-h">
<header class="uc-head"><p class="uc-no">Conversation</p><h2 id="discussion-h">Comments on {esc(uc_tag(bid))}</h2></header>
{body}
</section>'''


def board_page(i, b, tensions, err):
    bid, depth = b["id"], slug(b["id"]).count("/") + 1
    rel = "../" * depth
    ts = tensions_for(bid, tensions)
    cited = [q for q in QUOTES if bid in q["boards"]]
    hist = git_history(f"use-cases/{bid}.json")
    prev = f'<a href="{rel}{slug(BOARDS[i - 1]["id"])}/index.html">← {esc(BOARDS[i - 1]["no"])}</a>' if i else "<span></span>"
    nxt = f'<a href="{rel}{slug(BOARDS[i + 1]["id"])}/index.html">{esc(BOARDS[i + 1]["no"])} →</a>' if i + 1 < len(BOARDS) else "<span></span>"
    rev = (f'Revision {hist["n"]}, {day(hist["date"])} (<code>{hist["sha"]}</code>)' if hist else "Revision history on GitHub")
    ev = ('<ul class="quotes">' + "".join(quote_li(q, rel) for q in cited) + "</ul>") if cited else \
        '<p class="prose">This board quotes no one directly yet.</p>'
    key = bf.KEY_HTML if bid == "k0" else f'<p class="prose">Read against the <a href="{rel}k0/index.html">K0 key diagram</a>: every case is K0 with the lanes renamed and the slots filled.</p>'
    body = f'''<p class="pager">{prev}{nxt}</p>
{key}
{bf.section(b)}
<p class="actions"><span class="rev">{rev}</span><a href="{GH}/commits/main/use-cases/{bid}.json">History</a><a href="{GH}/edit/main/use-cases/{bid}.json">Suggest an edit</a><a href="{rel}assets/boards/{bid}.svg">SVG</a><a href="{rel}assets/boards/{bid}.png">PNG</a></p>
{tension_html(bid, ts, err)}
<section class="uc" id="evidence" aria-labelledby="evidence-h">
<header class="uc-head"><p class="uc-no">Evidence</p><h2 id="evidence-h">Quotes cited on this board</h2>
<p class="instance">{len(cited)} of {len(QUOTES)} recorded quotes. Times are offsets into the meeting recording. <a href="{rel}evidence/index.html">Search every quote</a>.</p></header>
{ev}
</section>
{discussion_html(bid)}'''
    title = f'{b["no"]}: {b["title"]}' if bid != "k0" else "K0: the x402 spine with identity slots"
    return shell(f"{title} · x402 Identity WG", re.sub(r"<[^>]+>", "", b["instance"])[:200], depth, body,
                 slug(bid) + "/", image=f"assets/boards/{bid}.png")


def index_page(tensions, err):
    def row(b):
        ts = tensions_for(b["id"], tensions)
        code, label = status(ts)
        cls = ' class="unrev"' if b.get("unreviewed") else ""
        note = "unreviewed · " if b.get("unreviewed") else ""
        return (f'<li><a href="{slug(b["id"])}/index.html"{cls}><span class="ix-uc">{esc(b["no"])}</span>'
                f'<span class="ix-name">{esc(b["title"])}</span><span class="ix-n st-{code}">{note}tensions: {label}</span></a></li>')
    n_open = sum(1 for t in tensions if t["open"] and t["blocking"])
    body = f'''<header class="mast">
  <p class="eyebrow">x402 Identity WG · draft for comment</p>
  <h1>Use cases, drawn as payment flows</h1>
  <p class="count">1 key diagram · {len(BOARDS) - 1} cases · {len(QUOTES)} quotes on record · {n_open} open tensions</p>
  <p class="topline">Each case is one x402 payment drawn as a swimlane, with the places identity enters marked as lettered slots. Open a case to read it, comment on it, and see what must be settled before it is done.</p>
</header>
<nav aria-label="Use cases"><ol class="index">{"".join(row(b) for b in BOARDS)}</ol></nav>
<section class="uc" aria-labelledby="how-h">
<header class="uc-head"><p class="uc-no">Take part</p><h2 id="how-h">Three ways to respond</h2></header>
<dl class="sheet">
<div class="frow"><dt>Comment</dt><dd>Every case page ends with a comment thread. Sign in with GitHub; threads are stored in this repository’s <a href="{GH}/discussions">Discussions</a>.</dd></div>
<div class="frow"><dt>Raise a tension</dt><dd>When two needs conflict, log it from the case page. Each tension is a <a href="{GH}/issues?q=label%3Atension">GitHub issue</a>; a case is done when none is open.</dd></div>
<div class="frow"><dt>Suggest an edit</dt><dd>Each case is one file under <a href="{GH}/tree/main/use-cases">use-cases/</a>. Edit it on GitHub and open a pull request; the file’s history is the case’s version history.</dd></div>
</dl>
</section>
<section class="uc" aria-label="Method">
<header class="uc-head"><p class="uc-no">Method</p><h2>How these were drawn</h2></header>
<p class="prose">Protocol messages and header names come from the x402 v2 specification. Slot placements come from the Oct 13 meeting, with the Oct 27 feedback applied (see the <a href="changes/index.html">change log</a>). A solid arrow is always one of the eight protocol messages, in the specification’s direction; anything the working group has not decided is dashed. Every build re-checks every arrow and fails if one breaks that rule.</p>
</section>'''
    return shell("x402 Identity WG · use cases", "x402 payment flows drawn as swimlanes, open for comment by the Identity Working Group.",
                 0, body, "", image="assets/boards/k0.png")


