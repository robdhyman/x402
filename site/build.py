#!/usr/bin/env python3
"""Build the public use-case site into _site/.

  python3 site/build.py              -> _site/ (open _site/index.html, or serve the folder)

Inputs: use-cases/*.json (the boards), evidence/quotes.json and changes.json (generated by
tools/extract_quotes.py), site/config.json (repo, giscus ids, discussion numbers), and the
repo's GitHub Issues labelled `tension` (fetched at build time; set GITHUB_TOKEN in CI).
The build fails if any arrow breaks the x402 message whitelist (boards/verify_arrows.py).
"""
import contextlib, datetime, io, json, os, re, shutil, subprocess, sys, urllib.request
from zoneinfo import ZoneInfo

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, os.path.join(ROOT, "boards"))
import build_family as bf
import verify_arrows

OUT = os.path.join(ROOT, "_site")
CFG = json.load(open(os.path.join(ROOT, "site", "config.json")))
REPO = CFG["repo"]
GH = f"https://github.com/{REPO}"
EV = json.load(open(os.path.join(ROOT, "evidence", "quotes.json"), encoding="utf-8"))
CHANGES = json.load(open(os.path.join(ROOT, "evidence", "changes.json"), encoding="utf-8"))
QUOTES = EV["quotes"]
BOARDS = [bf.K0] + bf.CASES
esc = bf.esc
MONTHS = ["Jan", "Feb", "Mar", "Apr", "May", "Jun", "Jul", "Aug", "Sep", "Oct", "Nov", "Dec"]


def day(d):
    y, m, dd = d.split("-")
    return f"{MONTHS[int(m) - 1]} {int(dd)}, {y}"


def slug(bid):
    m = re.match(r"uc(\d+)-(\d+)([a-z]?)$", bid)
    return f"uc/{m.group(1)}.{m.group(2)}{m.group(3)}" if m else bid


def uc_tag(bid):
    return "K0" if bid == "k0" else "UC" + slug(bid)[3:]


def git_history(path):
    try:
        out = subprocess.run(["git", "log", "--follow", "--format=%h|%ad", "--date=short", "--", path],
                             cwd=ROOT, capture_output=True, text=True, timeout=30).stdout.strip().split("\n")
        out = [l for l in out if l]
        return {"n": len(out), "sha": out[0].split("|")[0], "date": out[0].split("|")[1]} if out else None
    except Exception:
        return None


def fetch_tensions():
    """All issues labelled `tension`, open and closed. Returns (issues, error)."""
    url = f"https://api.github.com/repos/{REPO}/issues?labels=tension&state=all&per_page=100"
    req = urllib.request.Request(url, headers={"Accept": "application/vnd.github+json", "User-Agent": "x402-uc-site"})
    token = os.environ.get("GITHUB_TOKEN")
    if token:
        req.add_header("Authorization", f"Bearer {token}")
    try:
        items = json.load(urllib.request.urlopen(req, timeout=30))
    except Exception as e:
        return [], str(e)
    out = []
    for it in items:
        if "pull_request" in it:
            continue
        labels = [l["name"] for l in it["labels"]]
        out.append({"n": it["number"], "title": it["title"], "open": it["state"] == "open", "url": it["html_url"],
                    "labels": labels, "comments": it["comments"], "blocking": "non-blocking" not in labels})
    return sorted(out, key=lambda t: (not t["open"], t["n"])), None


def tensions_for(bid, tensions):
    t = uc_tag(bid).lower()
    return [x for x in tensions if ("uc:" + t[2:] if bid != "k0" else "uc:k0") in [l.lower() for l in x["labels"]]
            or x["title"].lower().startswith("[" + t + "]")]


def status(ts):
    blocking = [t for t in ts if t["open"] and t["blocking"]]
    if blocking:
        return "open", f"{len(blocking)} open"
    if ts:
        return "settled", "settled"
    return "none", "none logged"


